export type I18nKey = keyof (typeof strings)['en'];

/** Every locale the UI offers, in display order. */
export const supportedLocales: { value: Locale; nativeLabel: string; englishLabel: string }[] = [
    { value: 'en', nativeLabel: 'English', englishLabel: 'English' },
    { value: 'hi', nativeLabel: 'हिन्दी', englishLabel: 'Hindi' },
    { value: 'te', nativeLabel: 'తెలుగు', englishLabel: 'Telugu' },
    { value: 'mr', nativeLabel: 'मराठी', englishLabel: 'Marathi' },
    { value: 'ta', nativeLabel: 'தமிழ்', englishLabel: 'Tamil' },
    { value: 'gu', nativeLabel: 'ગુજરાતી', englishLabel: 'Gujarati' },
    { value: 'bn', nativeLabel: 'বাংলা', englishLabel: 'Bengali' },
];

function isLocale(value: string | null): value is Locale {
    return supportedLocales.some((option) => option.value === value);
}

export function getLocale(): Locale {
    if (typeof window === 'undefined') return 'en';

    const stored = window.localStorage.getItem(STORAGE_KEY);

    return isLocale(stored) ? stored : 'en';
}

export function setLocale(locale: Locale): void {
    window.localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale;
}

export function translate(locale: Locale, key: I18nKey): string {
    return strings[locale][key] ?? strings.en[key] ?? key;
}

export function useLocale() {
    const [locale, setLocaleState] = useState<Locale>(() => getLocale());

    useEffect(() => {
        document.documentElement.lang = locale;
    }, [locale]);

    const updateLocale = useCallback((next: Locale) => {
        setLocale(next);
        setLocaleState(next);
    }, []);

    const t = useCallback((key: I18nKey) => translate(locale, key), [locale]);

    return { locale, updateLocale, t };
}

export function initializeLocale(): void {
    if (typeof window === 'undefined') return;
    document.documentElement.lang = getLocale();
}